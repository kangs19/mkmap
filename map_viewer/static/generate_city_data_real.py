def build_output():
    """모든 품목의 city data를 단일 JSON으로 합산"""
    result = {}
    for item_code, muni_data in ITEM_DATA.items():
        result[item_code] = {}
        for city_code, vals in muni_data.items():
            if city_code not in MUNI:
                print(f"WARNING: {city_code} not in MUNI map (item={item_code})")
                continue
            result[item_code][city_code] = {
                "name": MUNI[city_code],
                "sido": SIDO_OF[city_code],
                **vals,
            }
    return result


if __name__ == "__main__":
    out = build_output()
    out_path = Path(__file__).parent / "city_agri_data.json"
    out_path.write_text(json.dumps(out, ensure_ascii=False, indent=2), encoding="utf-8")

    total_entries = sum(len(v) for v in out.values())
    print(f"✅ city_agri_data.json 생성 완료")
    print(f"   품목수: {len(out)}, 총 시군구 엔트리: {total_entries}")
    for code, cities in out.items():
        print(f"   {code}: {len(cities)}개 시군구")
